"""
compute_standard_metrics.py

Computes Sensitivity, Precision, (partial) Specificity, and Spearman rank
correlation for the 10-episode clean batch, from data already generated by
grade_episode.py (all_receipts.csv) and the raw agent logs. No new agent
runs, no LLM calls - purely derived from existing scored data.

Scope, and why:
- Sensitivity/Precision (A1/A2/A3): match_status ([matched]/[missed_by_model]/
  [hallucinated_by_model]) already gives TP/FN/FP per finding, diagnosis,
  and action - straightforward confusion-matrix arithmetic.
- Specificity (A1 Findings only): requires true negatives, which only exist
  where the radiologist explicitly documented a pertinent negative (e.g.
  "No pneumothorax is seen") and the model correctly reproduced it. Detected
  via a negation-phrase heuristic on the item text. This is a PARTIAL
  specificity - it's bounded to the closed set of negatives radiologists
  chose to document, not the full open-world "everything not mentioned",
  which chest X-ray free text has no closed label space for (unlike
  CheXpert's fixed 14-category structure). Not computed for A2/A3, where
  the concept doesn't map as cleanly (e.g. A3's "withhold antibiotics" is
  itself a real recommended action, not an absence-placeholder).
- Spearman (A3 Follow-up only): gold's generated_action_ids is a
  semicolon-ordered list that (checked by hand) reads as priority-ordered
  (urgent actions first). The agent's real selection order is already
  logged via step numbers in log.jsonl. Not computed for A2 (diagnosis
  order isn't a structured field - it's embedded in free-text Impression
  prose, unsafe to extract reliably) or A1 (findings aren't meaningfully
  orderable the same way).
"""

import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
sys.path.insert(0, str(Path(__file__).parent.parent))

from grade_process import _CATALOG, _match_action_id  # noqa: E402
from grade_episode import _lookup_gold  # noqa: E402

ROOT = Path(__file__).parent
ALL_RECEIPTS_CSV = ROOT / "all_receipts.csv"
EPISODES_DIR = ROOT / "episodes"

EPISODES = {
    "GRDN004RP5BFHE0T_2009-06-01_1785991219": ("GRDN004RP5BFHE0T", "2009-06-01"),
    "GRDN004RP5BFHE0T_2009-06-15_1785992551": ("GRDN004RP5BFHE0T", "2009-06-15"),
    "GRDN004RP5BFHE0T_2011-09-01_1785989933": ("GRDN004RP5BFHE0T", "2011-09-01"),
    "GRDN006MCYEVYFE8_2011-07-25_1785992166": ("GRDN006MCYEVYFE8", "2011-07-25"),
    "GRDN006VFINFR877_2013-03-25_1785991582": ("GRDN006VFINFR877", "2013-03-25"),
    "GRDN00BE97VCHW4E_2025-01-05_1785992661": ("GRDN00BE97VCHW4E", "2025-01-05"),
    "GRDN00BJ2R8QRO0L_2013-04-02_1785990708": ("GRDN00BJ2R8QRO0L", "2013-04-02"),
    "GRDN00BJ2R8QRO0L_2016-03-29_1785990362": ("GRDN00BJ2R8QRO0L", "2016-03-29"),
    "GRDN00BKCEOKC7S1_2024-01-12_1785991400": ("GRDN00BKCEOKC7S1", "2024-01-12"),
    "GRDN00BKCEOKC7S1_2025-02-12_1785991963": ("GRDN00BKCEOKC7S1", "2025-02-12"),
}

_MATCH_STATUS_RE = re.compile(r"^\[(\w+)\]\s*(.*)$")
_NEGATION_RE = re.compile(
    r"\bno \b|\bno\.\b|\bwithout\b|\bclear\b|\bnormal\b|\bwithin normal limits\b|"
    r"\bno evidence of\b|\bnot seen\b|\bunremarkable\b|\bnegative for\b",
    re.IGNORECASE,
)


def _dedupe_items(axis_label: str) -> dict[str, list[dict]]:
    """One row per unique (episode, item) pair, not one per sub-metric row -
    the sub-metric explosion would inflate every count 7-9x."""
    seen: dict[tuple[str, str], dict] = {}
    with ALL_RECEIPTS_CSV.open() as f:
        r = csv.DictReader(f)
        for row in r:
            if row["episode_dir"] not in EPISODES:
                continue
            if row["axis"] != axis_label:
                continue
            key = (row["episode_dir"], row["item"])
            if key in seen:
                continue
            m = _MATCH_STATUS_RE.match(row["item"])
            if not m:
                continue
            status, desc = m.group(1), m.group(2)
            seen[key] = {"episode": row["episode_dir"], "status": status, "desc": desc}
    by_episode = defaultdict(list)
    for (ep, _), v in seen.items():
        by_episode[ep].append(v)
    return by_episode


def sensitivity_precision(axis_label: str, noun: str) -> None:
    by_episode = _dedupe_items(axis_label)
    tp = fn = fp = 0
    for items in by_episode.values():
        for it in items:
            if it["status"] == "matched":
                tp += 1
            elif it["status"] == "missed_by_model":
                fn += 1
            elif it["status"] == "hallucinated_by_model":
                fp += 1
    sensitivity = tp / (tp + fn) if (tp + fn) else float("nan")
    precision = tp / (tp + fp) if (tp + fp) else float("nan")
    n_items = tp + fn + fp
    print(f"{axis_label} ({noun}s): n={n_items}  TP={tp} FN={fn} FP={fp}")
    print(f"  Sensitivity (recall): {sensitivity:.3f}")
    print(f"  Precision:            {precision:.3f}")
    return sensitivity, precision, tp, fn, fp


def specificity_a1() -> None:
    by_episode = _dedupe_items("A1 Findings")
    tn = fp = 0
    tn_examples, fp_examples = [], []
    for items in by_episode.values():
        for it in items:
            is_negation = bool(_NEGATION_RE.search(it["desc"]))
            if it["status"] == "matched" and is_negation:
                tn += 1
                if len(tn_examples) < 3:
                    tn_examples.append(it["desc"])
            elif it["status"] == "hallucinated_by_model":
                fp += 1
                if len(fp_examples) < 3:
                    fp_examples.append(it["desc"])
    specificity = tn / (tn + fp) if (tn + fp) else float("nan")
    print(f"A1 Findings partial specificity: TN={tn} (matched pertinent negatives) FP={fp} (hallucinated)")
    print(f"  Specificity (partial, closed to documented negatives): {specificity:.3f}")
    print(f"  TN examples: {tn_examples}")
    print(f"  FP examples: {fp_examples}")
    return specificity, tn, fp


def spearman_a3() -> None:
    """Per-episode Spearman rank correlation between gold's generated_action_ids
    order and the agent's real select_action call order (via log.jsonl step
    numbers), restricted to actions present in both lists (matched actions).
    Simple no-ties formula: rho = 1 - 6*sum(d^2) / (n*(n^2-1))."""
    results = []
    for ep_dir, (pid, visit_date) in EPISODES.items():
        gold = _lookup_gold(pid, visit_date)
        if gold is None or not gold.gold_action_ids:
            continue
        gold_order = list(gold.gold_action_ids)

        log_path = EPISODES_DIR / ep_dir / "log.jsonl"
        if not log_path.exists():
            continue
        agent_order = []
        with log_path.open() as f:
            import json
            for line in f:
                entry = json.loads(line)
                if entry.get("type") == "select_action":
                    action_id = _match_action_id(entry.get("level_2", ""))
                    if action_id:
                        agent_order.append(action_id)

        gold_rank = {a: i for i, a in enumerate(gold_order)}
        agent_rank = {a: i for i, a in enumerate(agent_order)}
        common = [a for a in gold_order if a in agent_rank]
        n = len(common)
        if n < 2:
            continue
        d2_sum = sum((gold_rank[a] - agent_rank[a]) ** 2 for a in common)
        rho = 1 - (6 * d2_sum) / (n * (n ** 2 - 1))
        results.append((ep_dir, n, rho))
        print(f"  {ep_dir}: n_common={n}, gold_order={gold_order}, agent_order={agent_order}, rho={rho:.3f}")

    if results:
        avg_rho = sum(r[2] for r in results) / len(results)
        print(f"\nA3 Spearman rank correlation: computable for {len(results)}/10 episodes "
              f"(needs >=2 actions in common between gold and agent selections)")
        print(f"  Average rho: {avg_rho:.3f}")
    else:
        print("A3 Spearman: no episode had >=2 common actions to correlate.")
    return results


